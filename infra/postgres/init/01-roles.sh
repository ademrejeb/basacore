#!/bin/bash
# Runtime role for the API. It is deliberately NOT the database owner and has
# neither SUPERUSER nor BYPASSRLS, so row-level security is actually enforced.
set -euo pipefail

: "${POSTGRES_APP_USER:?missing POSTGRES_APP_USER}"
: "${POSTGRES_APP_PASSWORD:?missing POSTGRES_APP_PASSWORD}"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-SQL
  CREATE ROLE ${POSTGRES_APP_USER} LOGIN PASSWORD '${POSTGRES_APP_PASSWORD}'
    NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
  GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${POSTGRES_APP_USER};
  GRANT USAGE ON SCHEMA public TO ${POSTGRES_APP_USER};
  ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_USER} IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${POSTGRES_APP_USER};
  ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_USER} IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO ${POSTGRES_APP_USER};
SQL
